CREATE TABLE mentions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    chef_id BIGINT NOT NULL REFERENCES chefs(id),
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id),
    video_id VARCHAR(11) NOT NULL REFERENCES videos(id),
    restaurant_candidate_id BIGINT REFERENCES restaurant_candidates(id),
    mention_type VARCHAR(20) CHECK (mention_type IN ('REGULAR','RECOMMENDED','VISITED','MENTIONED')),
    timestamp_seconds INTEGER CHECK (timestamp_seconds >= 0),
    verification_status VARCHAR(20) NOT NULL CHECK (verification_status IN ('PENDING','APPROVED','REJECTED')),
    evidence TEXT NOT NULL CHECK (length(trim(evidence)) > 0),
    review_note TEXT,
    reviewed_by BIGINT REFERENCES admin_users(id),
    reviewed_at TIMESTAMPTZ,
    UNIQUE NULLS NOT DISTINCT (chef_id,restaurant_id,video_id,mention_type),
    CHECK (verification_status <> 'APPROVED' OR
        (mention_type IS NOT NULL AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL
         AND review_note IS NOT NULL AND length(trim(review_note)) > 0))
);
CREATE INDEX mention_relations_candidate_idx ON mentions(restaurant_candidate_id);
CREATE INDEX mention_relations_restaurant_idx ON mentions(restaurant_id,verification_status);
CREATE INDEX mention_relations_video_idx ON mentions(video_id);

-- Retain V1 evidence and old review metadata as an immutable archive.
CREATE FUNCTION reject_legacy_candidate_writes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Legacy candidate archive is read-only'; END $$;
CREATE TRIGGER legacy_candidates_read_only BEFORE INSERT OR UPDATE OR DELETE
ON legacy_mention_candidates FOR EACH STATEMENT EXECUTE FUNCTION reject_legacy_candidate_writes();
